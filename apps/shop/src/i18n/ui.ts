/*
 * Dates are written by the browser in English — "25 Sept 2026", "Friday" —
 * and then read out in Bangla. Digits alone left "Jun ২০২৬": half of each.
 * So the names of the months and the days go over with the digits.
 */
const BN_WORDS: Record<string, string> = {
  January: 'জানুয়ারি', February: 'ফেব্রুয়ারি', March: 'মার্চ', April: 'এপ্রিল', June: 'জুন',
  July: 'জুলাই', August: 'আগস্ট', September: 'সেপ্টেম্বর', October: 'অক্টোবর',
  November: 'নভেম্বর', December: 'ডিসেম্বর',
  Jan: 'জানু', Feb: 'ফেব্রু', Mar: 'মার্চ', Apr: 'এপ্রিল', May: 'মে', Jun: 'জুন', Jul: 'জুলাই',
  Aug: 'আগস্ট', Sept: 'সেপ্টে', Sep: 'সেপ্টে', Oct: 'অক্টো', Nov: 'নভে', Dec: 'ডিসে',
  Saturday: 'শনিবার', Sunday: 'রবিবার', Monday: 'সোমবার', Tuesday: 'মঙ্গলবার',
  Wednesday: 'বুধবার', Thursday: 'বৃহস্পতিবার', Friday: 'শুক্রবার',
  am: 'এএম', pm: 'পিএম',
};
const BN_WORD_RX = new RegExp(`\\b(${Object.keys(BN_WORDS).join('|')})\\b`, 'g');

/** Latin digits, month and day names to Bangla. Only for what is read, never for identifiers. */
export function bnNumerals(s: string): string {
  return bnDigits(s).replace(BN_WORD_RX, (w) => BN_WORDS[w] ?? w);
}

